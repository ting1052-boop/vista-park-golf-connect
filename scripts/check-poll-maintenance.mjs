import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import ts from "typescript";

const source = fs.readFileSync(new URL("../src/lib/poll-maintenance.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const exports = {};
let now = 0;
vm.runInNewContext(compiled, { exports, Date: { now: () => now } });
const run = exports.runPollMaintenance;
let calls = 0;
const work = async () => ++calls;
assert.equal(await run("store-a", work), 1);
assert.equal(await run("store-a", work), undefined);
assert.equal(await run("store-b", work), 2);
now = 30_000;
assert.equal(await run("store-a", work), 3);
let release;
const pending = run("concurrent", () => new Promise((resolve) => { calls++; release = resolve; }));
await Promise.resolve();
const second = run("concurrent", work);
release("done");
assert.equal(await pending, "done");
assert.equal(await second, undefined);
assert.equal(calls, 4);
await assert.rejects(run("retry", async () => { throw new Error("offline"); }), /offline/);
assert.equal(await run("retry", work), 5);
console.log("Poll maintenance: interval, store isolation, concurrency and failure retry passed.");
